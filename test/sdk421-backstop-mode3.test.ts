/**
 * SDK#421 — tag 111 mode 3 (RESTORE-FROM-PNL) was unreachable.
 *
 * The deployed v2.2 wrapper implements four modes of `InsuranceBackstopDraw`; the SDK admitted
 * three. Mode 3 was blocked twice: the signature was `mode: 0 | 1 | 2` (a compile error for any
 * consumer) and `intIn("mode", mode, 0, 2)` threw at runtime, so even a cast could not get past it.
 *
 * The program documents mode 3 as the mode a keeper should try first, with a fallback:
 *
 *   KEEPER NOTE (W4-4): mode 3 can REVERT where mode 1 would succeed (the engine's capacity read
 *   returns an error, not 0, on an inconsistent source ledger or a failed validation). A keeper
 *   that gets a mode-3 error must fall back to mode 1 in the same sweep.
 *
 * Mode 3 shares mode 1's equity room, so it does NOT repay past the R-6 floor
 * ("conversion neutrality means PnL and capital draw on the same room"). It differs only when the
 * LP's capital is below the repayable amount while it holds unconverted, source-backed profit,
 * where mode 1 is capped at min(want, capital).
 *
 * NOTE ON COVERAGE: there is deliberately no golden parity vector for mode 3 here. The
 * `V22_VECTORS` table in v22-vector-inputs.ts is checked against test/fixtures/v22-parity.json,
 * which is generated by scripts/v22-parity/sdk_v22_parity.rs against a pinned wrapper crate. Adding
 * an entry without regenerating that fixture makes v22-parity.test.ts fail on a missing key. A
 * mode-3 golden vector should be added the next time those fixtures are regenerated; these tests
 * cover the encoder's bytes and bounds in the meantime.
 */
import { Keypair, PublicKey } from "@solana/web3.js";
import { describe, expect, it } from "vitest";
import * as W from "../src/abi/v22-wire.js";
import * as B from "../src/solana/v22.js";

const hex = (b: Uint8Array) => Buffer.from(b).toString("hex");
const pk = () => Keypair.generate().publicKey;

describe("SDK#421: tag 111 accepts mode 3 (RESTORE-FROM-PNL)", () => {
  it("BackstopMode names all four modes the program implements", () => {
    expect(W.BackstopMode).toMatchObject({ Draw: 0, Restore: 1, Propose: 2, RestoreFromPnl: 3 });
  });

  it("encodes mode 3 as the documented 18 bytes: [111, 3, max_amount u128 LE]", () => {
    const bytes = W.encodeInsuranceBackstopDrawV22(W.BackstopMode.RestoreFromPnl, 9n);
    expect(bytes.length).toBe(18);
    expect(bytes[0]).toBe(0x6f); // tag 111
    expect(bytes[1]).toBe(3);
    // 9 as a little-endian u128
    expect(hex(bytes)).toBe("6f03" + "09" + "00".repeat(15));
  });

  it("mode 3 differs from mode 1 in exactly one byte", () => {
    const one = W.encodeInsuranceBackstopDrawV22(W.BackstopMode.Restore, 9n);
    const three = W.encodeInsuranceBackstopDrawV22(W.BackstopMode.RestoreFromPnl, 9n);
    expect(one.length).toBe(three.length);
    const differing = [...one].map((b, i) => (b === three[i] ? null : i)).filter((i) => i !== null);
    expect(differing).toEqual([1]);
  });

  it("still refuses out-of-range modes — the bound moved, it did not disappear", () => {
    expect(() => W.encodeInsuranceBackstopDrawV22(4 as never, 0n)).toThrow(/mode/);
    expect(() => W.encodeInsuranceBackstopDrawV22(255 as never, 0n)).toThrow(/mode/);
    expect(() => W.encodeInsuranceBackstopDrawV22(-1 as never, 0n)).toThrow(/mode/);
  });

  it("every one of the four modes round-trips to its own byte", () => {
    for (const m of [0, 1, 2, 3] as const) {
      expect(W.encodeInsuranceBackstopDrawV22(m, 0n)[1]).toBe(m);
    }
  });

  it("the instruction builder accepts mode 3 and carries the byte through", () => {
    const m: B.MarketV22 = { programId: pk(), market: pk(), registryDomain: 0, lpPortfolio: pk(), vaultLpExt: pk() };
    const ix = B.buildInsuranceBackstopDrawIxV22(m, pk(), W.BackstopMode.RestoreFromPnl, 0n);
    expect(ix.data[0]).toBe(0x6f);
    expect(ix.data[1]).toBe(3);
    expect(ix.data.length).toBe(18);
  });

  it("the builder's account list is identical for modes 1 and 3 (only the data byte changes)", () => {
    // Mode 3 is "RESTORE, but repay from profit first" -- it takes no extra accounts. Pinned so a
    // future account-list change for mode 3 has to be deliberate.
    const m: B.MarketV22 = { programId: pk(), market: pk(), registryDomain: 0, lpPortfolio: pk(), vaultLpExt: pk() };
    const cranker = pk();
    const one = B.buildInsuranceBackstopDrawIxV22(m, cranker, W.BackstopMode.Restore, 7n);
    const three = B.buildInsuranceBackstopDrawIxV22(m, cranker, W.BackstopMode.RestoreFromPnl, 7n);
    const keys = (i: typeof one) => i.keys.map((k) => `${k.pubkey.toBase58()}:${k.isSigner ? "s" : "-"}${k.isWritable ? "w" : "-"}`);
    expect(keys(three)).toEqual(keys(one));
    expect(three.programId.equals(one.programId)).toBe(true);
  });

  it("an extra tail is still appended read-only for mode 3", () => {
    const m: B.MarketV22 = { programId: pk(), market: pk(), registryDomain: 0, lpPortfolio: pk(), vaultLpExt: pk() };
    const feed = pk();
    const ix = B.buildInsuranceBackstopDrawIxV22(m, pk(), W.BackstopMode.RestoreFromPnl, 0n, [feed]);
    const last = ix.keys[ix.keys.length - 1] as { pubkey: PublicKey; isSigner: boolean; isWritable: boolean };
    expect(last.pubkey.equals(feed)).toBe(true);
    expect(last.isWritable).toBe(false);
    expect(last.isSigner).toBe(false);
  });
});
